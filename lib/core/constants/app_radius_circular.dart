/// A utility class that defines standardized circular border radii
/// used across the application for consistent UI design.
///
/// This class cannot be instantiated.
/// Access the predefined radius values through the static constants.
class AppRadiusCircular {
  AppRadiusCircular._();

  /// Extra-small radius (4px)
  static const double xs = 4;

  /// Small radius (8px)
  static const double s = 8;

  /// Medium radius (12px)
  static const double m = 12;

  /// Large radius (16px)
  static const double l = 16;

  /// Extra-large radius (24px)
  static const double xl = 24;

  /// Extra-super-large radius (28px)
  static const double xsl = 28;
}
